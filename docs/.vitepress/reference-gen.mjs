// Generates reference tables in docs/reference/_generated/ from the real Java source, so the
// documentation of the YAML contract schema, matcher enums, predefined regexes and test
// frameworks can never drift from the code.
//
// SINGLE SOURCE OF TRUTH: both the *names* and the *descriptions* come from the Java source —
// field/enum-constant names and their Javadoc. There is no description registry here. The
// generator FAILS if any documented field or enum constant has no Javadoc, so a schema change
// forces the docs (the Javadoc) to be updated. Run:
//   npm run docs:gen          # (re)write the partials
//   npm run docs:gen:check    # write + fail if anything changed (CI gate)
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'docs', 'reference', '_generated');
const YAML_CONTRACT = 'stubborn-contract-verifier/src/main/java/sh/stubborn/contract/verifier/converter/YamlContract.java';
const TEST_FRAMEWORK = 'stubborn-contract-verifier/src/main/java/sh/stubborn/contract/verifier/config/TestFramework.java';

const read = (p) => readFileSync(join(ROOT, p), 'utf8').split('\n');

let failed = false;
const fail = (msg) => { console.error(`[reference-gen] ${msg}`); failed = true; };

// --- Java source parsing (line based) ------------------------------------------------------

// Inclusive [start,end] line indices of the body of `... <keyword> <name> {`.
function bodyRange(lines, header) {
	const startLine = lines.findIndex((l) => l.includes(header));
	if (startLine < 0) throw new Error(`not found: ${header}`);
	let depth = 0, opened = false;
	for (let i = startLine; i < lines.length; i++) {
		for (const ch of lines[i]) {
			if (ch === '{') { depth++; opened = true; }
			else if (ch === '}') { depth--; if (opened && depth === 0) return [startLine + 1, i - 1]; }
		}
	}
	throw new Error(`unbalanced: ${header}`);
}

// The Javadoc immediately preceding line `i`, as markdown, or null.
function docBefore(lines, i) {
	let j = i - 1;
	while (j >= 0 && lines[j].trim() === '') j--;
	if (j < 0 || !lines[j].trim().endsWith('*/')) return null;
	let k = j;
	while (k >= 0 && !lines[k].includes('/**')) k--;
	if (k < 0) return null;
	let text = lines.slice(k, j + 1).join('\n');
	text = text.replace(/\/\*\*/, '').replace(/\*\//, '');
	text = text.split('\n').map((l) => l.replace(/^\s*\*\s?/, '').trim()).join(' ');
	text = text.replace(/\{@code\s+([^}]+)\}/g, '`$1`').replace(/\{@link\s+([^}]+)\}/g, '`$1`');
	return text.replace(/\s+/g, ' ').trim();
}

// Public instance fields declared directly in a class body, with their Javadoc.
function fields(lines, header, stopAtNested = false) {
	const [s, e] = bodyRange(lines, header);
	const out = [];
	for (let i = s; i <= e; i++) {
		const line = lines[i];
		if (stopAtNested && /^\s*(public\s+)?(static\s+)?(class|enum)\s/.test(line)) break;
		if (/\bstatic\b/.test(line)) continue;
		const m = line.match(/^\s*public\s+(?:@Nullable\s+)?.*?\b(\w+)\s*(?:=[^=]|;)/);
		if (!m) continue;
		const doc = docBefore(lines, i);
		if (!doc) fail(`${header.replace(/[{]/g, '').trim()} field '${m[1]}' has no Javadoc — add one (it is the single source of its docs).`);
		out.push([m[1], doc ?? '—']);
	}
	return out;
}

// Enum constants with their Javadoc.
function enumConsts(lines, name) {
	const [s, e] = bodyRange(lines, `enum ${name} {`);
	const out = [];
	for (let i = s; i <= e; i++) {
		const line = lines[i];
		if (line.includes(';')) break; // end of the constant list
		const m = line.match(/^\s*([A-Za-z_]\w*)\s*(?:\(|,|$)/);
		if (!m) continue;
		const doc = docBefore(lines, i);
		if (!doc) fail(`enum ${name}.${m[1]} has no Javadoc — add one.`);
		out.push([m[1], doc ?? '—']);
	}
	return out;
}

// --- rendering -----------------------------------------------------------------------------

const WARNING = '<!-- GENERATED by docs/.vitepress/reference-gen.mjs from the Java source (names + Javadoc) — do not edit by hand. Run `npm run docs:gen`. -->\n';
const table = (rows, header = ['Field', 'Description']) =>
	`${WARNING}| ${header[0]} | ${header[1]} |\n|---|---|\n${rows.map(([n, d]) => `| \`${n}\` | ${d} |`).join('\n')}\n`;

const yc = read(YAML_CONTRACT);
const tf = read(TEST_FRAMEWORK);

const outputs = {
	'yaml-top-level.md': table(fields(yc, 'class YamlContract {', true)),
	'yaml-request.md': table(fields(yc, 'class Request {')),
	'yaml-response.md': table(fields(yc, 'class Response {')),
	'yaml-input.md': table(fields(yc, 'class Input {')),
	'yaml-output-message.md': table(fields(yc, 'class OutputMessage {')),
	'yaml-matcher-entry.md': table(fields(yc, 'class BodyStubMatcher {')),
	'yaml-stub-matcher-types.md': table(enumConsts(yc, 'StubMatcherType'), ['`type` (request/stub side)', 'Description']),
	'yaml-test-matcher-types.md': table(enumConsts(yc, 'TestMatcherType'), ['`type` (response/test side)', 'Description']),
	'yaml-predefined-regex.md': table(enumConsts(yc, 'PredefinedRegex'), ['`predefined`', 'Description']),
	'test-frameworks.md': table(enumConsts(tf, 'TestFramework'), ['Value', 'Description']),
};

// --- drift guard: reference docs and example fixtures must not use schema names that don't
// exist in the model. ------------------------------------------------------------------------
const FORBIDDEN = ['predefinedRegex', 'messageFrom', 'messageBody', 'messageHeaders', 'urlPattern',
	'urlPathPattern', 'by_empty', 'iso_date_time_with_millis'];
function scanForbidden(dir, exts) {
	for (const entry of readdirSync(join(ROOT, dir), { withFileTypes: true })) {
		if (entry.isDirectory() || !exts.some((x) => entry.name.endsWith(x)) || dir.endsWith('_generated')) continue;
		const text = readFileSync(join(ROOT, dir, entry.name), 'utf8');
		for (const tok of FORBIDDEN)
			if (new RegExp(`\\b${tok}\\b`).test(text)) fail(`${dir}/${entry.name} uses '${tok}', which is not a real schema name.`);
	}
}
scanForbidden('docs/reference', ['.md']);
scanForbidden('docs/examples', ['.yml', '.yaml']);

if (failed) { console.error('[reference-gen] FAILED.'); process.exit(2); }
mkdirSync(OUT, { recursive: true });
for (const [file, content] of Object.entries(outputs)) writeFileSync(join(OUT, file), content);
console.log(`[reference-gen] wrote ${Object.keys(outputs).length} reference partials from the Java source.`);
